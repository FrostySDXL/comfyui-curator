"""Dependency-file contract tests.

The convenience install files are deliberately thin include shims so a fresh
documented install cannot drift from the source-of-truth ``.in`` files (most
notably, a dev install must include ``aiohttp`` for the real native HTTP tests).
"""

from __future__ import annotations

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
RUNTIME_IN = REPO_ROOT / "requirements.in"
DEV_IN = REPO_ROOT / "requirements-dev.in"
RUNTIME_TXT = REPO_ROOT / "requirements.txt"
DEV_TXT = REPO_ROOT / "requirements-dev.txt"
RUNTIME_LOCK = REPO_ROOT / "requirements-lock.txt"
DEV_LOCK = REPO_ROOT / "requirements-dev-lock.txt"

_REQUIREMENT_NAME_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)")


def _normalize(name: str) -> str:
    return name.strip().lower().replace("_", "-")


def _requirement_lines(path: Path):
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.split("#", 1)[0].strip()
        if line:
            yield line


def _direct_requirement_names(path: Path) -> set[str]:
    names: set[str] = set()
    for line in _requirement_lines(path):
        if line.startswith("-"):
            continue
        match = _REQUIREMENT_NAME_RE.match(line)
        if match:
            names.add(_normalize(match.group(1)))
    return names


def _include_paths(path: Path) -> list[Path]:
    includes = []
    for line in _requirement_lines(path):
        if line.startswith("-r "):
            includes.append((path.parent / line[3:].strip()).resolve())
    return includes


def _resolved_requirement_names(path: Path, seen: set[Path] | None = None) -> set[str]:
    path = path.resolve()
    seen = set() if seen is None else seen
    if path in seen:
        return set()
    seen.add(path)
    names = _direct_requirement_names(path)
    for include in _include_paths(path):
        names |= _resolved_requirement_names(include, seen)
    return names


def _locked_requirement_names(path: Path) -> set[str]:
    names: set[str] = set()
    for line in _requirement_lines(path):
        if line.startswith("-") or "==" not in line:
            continue
        names.add(_normalize(line.split("==", 1)[0]))
    return names


def test_runtime_convenience_file_only_includes_runtime_source():
    assert _include_paths(RUNTIME_TXT) == [RUNTIME_IN.resolve()]
    assert _direct_requirement_names(RUNTIME_TXT) == set()


def test_dev_convenience_file_only_includes_dev_source():
    assert _include_paths(DEV_TXT) == [DEV_IN.resolve()]
    assert _direct_requirement_names(DEV_TXT) == set()


def test_dev_source_layers_on_runtime_source_and_declares_aiohttp():
    assert _include_paths(DEV_IN) == [RUNTIME_IN.resolve()]

    dev_names = _resolved_requirement_names(DEV_IN)
    assert "aiohttp" in dev_names
    assert _resolved_requirement_names(RUNTIME_IN) <= dev_names


def test_dev_convenience_install_resolves_aiohttp_and_runtime_dependencies():
    names = _resolved_requirement_names(DEV_TXT)
    assert "aiohttp" in names
    assert _resolved_requirement_names(RUNTIME_IN) <= names


def test_runtime_lock_covers_every_runtime_requirement():
    assert _resolved_requirement_names(RUNTIME_IN) <= _locked_requirement_names(RUNTIME_LOCK)


def test_dev_lock_covers_every_dev_and_runtime_requirement():
    assert _resolved_requirement_names(DEV_IN) <= _locked_requirement_names(DEV_LOCK)


def test_dev_lock_is_resolved_on_the_minimum_supported_python():
    header = "\n".join(DEV_LOCK.read_text(encoding="utf-8").splitlines()[:8])
    assert "autogenerated by pip-compile with Python 3.10" in header
    assert "requirements-dev.in" in header
